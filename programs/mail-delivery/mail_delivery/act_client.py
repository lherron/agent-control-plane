"""The exact collaboration-ledger surface used by the mail kicker."""
from typing import Any, Protocol
from .act_contracts import WrkqLedgerRequestError, WrkqLedgerUnavailableError
from .act_types import (
    WrkqEnvelope, WrkqEnvelopePendingView, WrkqEnvelopePendingViewParams,
    WrkqEnvelopePresentParams, WrkqEnvelopePresentResult, WrkqEnvelopeFailParams,
    WrkqEnvelopeShowParams, WrkqMonitorEventsView, WrkqMonitorEventsViewParams,
)


class MailKickerLedger(Protocol):
    async def commit_wait(self, params: dict[str, Any]) -> dict[str, Any]: ...
    async def pending_view(self, params: WrkqEnvelopePendingViewParams) -> WrkqEnvelopePendingView: ...
    async def present(self, params: WrkqEnvelopePresentParams) -> WrkqEnvelopePresentResult: ...
    async def fail(self, params: WrkqEnvelopeFailParams) -> WrkqEnvelope: ...
    async def envelope_show(self, params: WrkqEnvelopeShowParams) -> WrkqEnvelope: ...
    async def events_view(self, params: WrkqMonitorEventsViewParams) -> WrkqMonitorEventsView: ...
    async def task_show(self, params: dict[str, str]) -> dict[str, str]: ...
