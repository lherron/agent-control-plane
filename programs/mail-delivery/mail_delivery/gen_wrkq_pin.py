"""Write `wrkq_pin.py` from ACP's installed `@wrkq/client`.

The protocol schema hash is never typed into source: it is read from
`node_modules/@wrkq/client/dist/protocol.js` of the canonical checkout, so
moving ACP's pin moves the Python client with the TypeScript one. The output
is git-ignored.
"""
import argparse
from pathlib import Path
import re

DEFAULT_CHECKOUT = Path.home() / 'praesidium/agent-control-plane'
PROTOCOL_JS = Path('node_modules/@wrkq/client/dist/protocol.js')
OUTPUT = Path(__file__).absolute().parent / 'wrkq_pin.py'


def read_pin(protocol_js):
    text = Path(protocol_js).read_text()
    values = {}
    for name in ('PROTOCOL_VERSION', 'PROTOCOL_SCHEMA_HASH'):
        found = re.findall(r'export const ' + name + r'\s*=\s*"([^"\\]+)"\s*;', text)
        if len(found) != 1:
            raise ValueError(f'{protocol_js}: expected one {name} string constant, found {len(found)}')
        values[name] = found[0]
    if not re.fullmatch(r'sha256:[0-9a-f]{64}', values['PROTOCOL_SCHEMA_HASH']):
        raise ValueError(f'{protocol_js}: PROTOCOL_SCHEMA_HASH is not a sha256 digest')
    return values


def write_pin(protocol_js, output=OUTPUT):
    values = read_pin(protocol_js)
    output = Path(output)
    staged = output.with_name(output.name + '.tmp')
    staged.write_text(
        f'"""Generated by gen_wrkq_pin.py from {protocol_js}. Do not edit or commit."""\n'
        f"PROTOCOL_VERSION = {values['PROTOCOL_VERSION']!r}\n"
        f"PROTOCOL_SCHEMA_HASH = {values['PROTOCOL_SCHEMA_HASH']!r}\n")
    staged.replace(output)
    return values


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--checkout', type=Path, default=DEFAULT_CHECKOUT)
    parser.add_argument('--output', type=Path, default=OUTPUT)
    args = parser.parse_args()
    values = write_pin(args.checkout / PROTOCOL_JS, args.output)
    print(f"{args.output}: {values['PROTOCOL_VERSION']} {values['PROTOCOL_SCHEMA_HASH']}")


if __name__ == '__main__':
    main()
