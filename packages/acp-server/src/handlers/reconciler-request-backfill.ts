import { randomUUID } from 'node:crypto'
import { badRequest, json } from '../http.js'
import { isRecord } from '../parsers/body.js'
import { isLoopbackPeer } from '../routing/peer.js'
import type { RouteHandler } from '../routing/route-context.js'

/** Trusted host-local operator boundary, NOT authenticated agent/Mable identity. */
function handler(mode: 'plan' | 'apply'): RouteHandler {
  return async ({ request, peer, deps }) => {
    if (!isLoopbackPeer(peer))
      return json({ error: { code: 'not_local', message: 'not found' } }, 404)
    if (request.headers.has('origin'))
      return json(
        { error: { code: 'browser_origin_denied', message: 'operator process required' } },
        403
      )
    if (
      request.headers.get('content-type')?.split(';')[0]?.trim().toLowerCase() !==
      'application/json'
    )
      badRequest('JSON content type required')
    let body: unknown
    try {
      body = await request.json()
    } catch {
      badRequest('request body must be valid JSON')
    }
    if (!isRecord(body)) badRequest('request body must be an object')
    const keys = Object.keys(body)
    if (
      mode === 'plan'
        ? keys.length !== 0
        : keys.length !== 2 ||
          !keys.includes('manifest') ||
          !keys.includes('expectedSha256') ||
          typeof body['expectedSha256'] !== 'string' ||
          !/^[a-f0-9]{64}$/.test(body['expectedSha256'])
    )
      badRequest('exact plan/apply body required')
    const capability = deps.requestBackfill
    if (!capability)
      return json(
        { error: { code: 'backfill_unavailable', message: 'reconciler maintenance unavailable' } },
        503
      )
    // Generated by host, never an actor/identity claim supplied in the request.
    const requestId = randomUUID()
    const reply =
      mode === 'plan'
        ? await capability.plan(requestId)
        : await capability.apply(body['manifest'], body['expectedSha256'] as string, requestId)
    const { status, ...result } = reply
    return json(result, status)
  }
}
export const handleRequestBackfillPlan = handler('plan')
export const handleRequestBackfillApply = handler('apply')
